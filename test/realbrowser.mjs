import { createRequire } from 'node:module';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--allow-file-access-from-files'] });
const page = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = []; page.on('pageerror', (e) => errs.push('pageerror ' + e.message));
await page.goto('file:///home/claude/isp-lab/dist/index.html');
await page.waitForTimeout(300);
const out = () => page.evaluate(() => { const d = document.querySelector('#out').getContext('2d').getImageData(0, 0, 400, 400).data; let h = 0; for (let i = 0; i < d.length; i++) h = (h * 31 + d[i]) | 0; return h; });
const h0 = await out();
await page.selectOption('#c-demosaic-method', 'amaze'); await page.waitForTimeout(300);
console.log('amaze changes output', h0 !== await out(), await page.textContent('#timing'));
await page.setInputFiles('#filefw', '/mnt/user-data/uploads/OLY_E_122_3101_0000_0000.BIN');
await page.waitForFunction(() => ['stock', 'modified', 'none'].includes(document.querySelector('#fw').dataset.kind) && document.querySelector('#fw').textContent !== 'No firmware loaded', null, { timeout: 120000 });
await page.waitForTimeout(500);
console.log('fw', await page.textContent('#fw'), '|', await page.textContent('#msg'), '|', await page.textContent('#timing'));
console.log('K', await page.inputValue('#c-sharpen-K ~ input[type=number]'), 'A', await page.inputValue('#c-sharpen-A ~ input[type=number]'), 'shift', await page.inputValue('#c-sharpen-shift ~ input[type=number]'), 'fail hidden', await page.isHidden('#fwfail'));
await page.selectOption('#c-sixaxis-mode', '1'); await page.fill('#c-shading-step ~ input[type=number]', '-5'); await page.waitForTimeout(400);
await page.screenshot({ path: '/tmp/r1.png', fullPage: false });
await page.fill('#c-shading-step ~ input[type=number]', '0'); await page.waitForTimeout(200);
// Collapse
const top = (s) => page.evaluate((q) => Math.round(document.querySelector(q).getBoundingClientRect().top + scrollY), s);
const hslBefore = await top('#panels-hsl'), capBefore = await top('#captures');
await page.click('#h-matrix ~ .fold'); await page.click('#h-levels ~ .fold'); await page.click('#h-sixaxis ~ .fold'); await page.waitForTimeout(200);
const hslAfter = await top('#panels-hsl');
const capMid = await top('#captures');
await page.click('#h-hsl ~ .fold'); await page.waitForTimeout(150);
const capAfter = await top('#captures');
console.log('hsl top', hslBefore, '->', hslAfter, '| captures', capBefore, '->', capMid, '->', capAfter);
console.log('matrix body hidden', await page.isHidden('#c-matrix-m0'), 'checkbox visible', await page.isVisible('#on-matrix'), 'tags hidden', await page.isHidden('#h-matrix .tags'), 'aria', await page.getAttribute('#h-matrix ~ .fold', 'aria-expanded'), await page.getAttribute('#h-matrix ~ .fold', 'aria-label'));
await page.click('#captures .fold'); await page.waitForTimeout(100);
console.log('captures body hidden', await page.isHidden('#log'));
await page.screenshot({ path: '/tmp/r2.png', fullPage: true });
await page.click('#h-matrix ~ .fold'); await page.waitForTimeout(100);
console.log('re-expanded', await page.isVisible('#c-matrix-m0'), 'errors', errs);
await b.close();
